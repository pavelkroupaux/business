import StyleDictionary from 'style-dictionary';

/**
 * Token names are chosen to be framework-agnostic (`space-6`, `font-size-2xl`),
 * but Tailwind v4 derives its utilities from specific CSS variable namespaces
 * (`--spacing-*`, `--text-*`, `--leading-*`, …).
 *
 * This table is the adapter between the two. It is a rename, not a second
 * scale — every value still comes from tokens/src, so there is nothing to keep
 * manually in sync.
 */
const TAILWIND_NAMESPACE = [
  ['font-letter-spacing-', 'tracking-'],
  ['font-line-height-', 'leading-'],
  ['font-family-', 'font-'],
  ['font-size-', 'text-'],
  ['motion-duration-', 'duration-'],
  ['motion-easing-', 'ease-'],
  ['size-container-', 'container-'],
  ['space-', 'spacing-'],
  // color-, radius-, shadow-, breakpoint-, font-weight- already match.
];

const toTailwindName = (name) => {
  for (const [from, to] of TAILWIND_NAMESPACE) {
    if (name.startsWith(from)) return to + name.slice(from.length);
  }
  return name;
};

/**
 * Emits a Tailwind v4 `@theme` block so Tailwind utilities are generated
 * directly from the token set — no duplicated scale in a JS config.
 */
StyleDictionary.registerFormat({
  name: 'css/tailwind-theme',
  format: ({ dictionary }) => {
    const lines = dictionary.allTokens.map(
      (t) => `  --${toTailwindName(t.name)}: ${t.value};`
    );
    return `/**\n * GENERATED by tokens/build.mjs — do not edit by hand.\n * Edit tokens/src/*.json and run \`npm run tokens\`.\n */\n@theme {\n${lines.join('\n')}\n}\n`;
  },
});

/**
 * Metadata feed for the style guide: keeps each token's path, CSS variable
 * name, resolved value and type, so the docs page is generated from the token
 * set itself and cannot drift from it.
 */
StyleDictionary.registerFormat({
  name: 'json/docs',
  format: ({ dictionary }) =>
    JSON.stringify(
      dictionary.allTokens.map((t) => ({
        path: t.path,
        group: t.path[0],
        name: t.name,
        cssVar: `--${t.name}`,
        tailwindVar: `--${toTailwindName(t.name)}`,
        value: t.value,
        type: t.type ?? t.$type ?? 'other',
      })),
      null,
      2
    ),
});

/**
 * Tailwind reads breakpoints from `--breakpoint-*`, colors from `--color-*`,
 * spacing from `--spacing-*`, etc. Our source names already align, so the
 * default `kebab` transform maps cleanly onto Tailwind's namespaces.
 */
export default {
  source: ['tokens/src/**/*.json'],
  platforms: {
    css: {
      transformGroup: 'css',
      buildPath: 'tokens/dist/',
      files: [
        {
          destination: 'variables.css',
          format: 'css/variables',
          options: { outputReferences: true },
        },
        {
          destination: 'theme.css',
          format: 'css/tailwind-theme',
        },
      ],
    },
    // Uses the CSS transform group so names stay kebab-case and line up with
    // the variables actually emitted into variables.css / theme.css.
    docs: {
      transformGroup: 'css',
      buildPath: 'tokens/dist/',
      files: [{ destination: 'tokens.docs.json', format: 'json/docs' }],
    },
    js: {
      transformGroup: 'js',
      buildPath: 'tokens/dist/',
      files: [
        { destination: 'tokens.js', format: 'javascript/es6' },
        { destination: 'tokens.json', format: 'json/flat' },
      ],
    },
  },
};
